// Package webapp carries the WhiteSoft web client inside the desktop binary.
//
// The client itself is unchanged: the same `public/` tree that `server.mjs`
// hosts is embedded here and served from an in-process HTTP server, so the
// desktop app runs exactly the same JavaScript — canvas, tools, `.note` reading
// and writing, PDF import, MathJax — without Node and without a folder next to
// the executable.
//
// The `web/` directory is generated from the repository's `public/` by
//
//	go generate ./...
//
// (see tools/copyweb).  It is not committed, so a fresh checkout has to run
// that once before the first build.
package webapp

import (
	"embed"
	"errors"
	"io/fs"
)

//go:generate go run ../../tools/copyweb -src ../../../public -dst ./web

//nolint:typecheck // web/ is generated by `go generate`
//go:embed all:web
var embedded embed.FS

// FS is the web client, rooted so that "index.html" is at the top.
func FS() (fs.FS, error) {
	root, err := fs.Sub(embedded, "web")
	if err != nil {
		return nil, err
	}
	// A build that skipped `go generate` would otherwise embed nothing and show
	// an empty window with no clue why.
	if _, err := fs.Stat(root, "index.html"); err != nil {
		return nil, errors.New("网页资源没有打包进程序：请先在 desktop 目录运行 `go generate ./...`")
	}
	return root, nil
}
